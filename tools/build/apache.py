"""Apache .htaccess rendering."""

from __future__ import annotations

from urls import page_prefix


def htaccess_404_path(ctx, lang: str) -> str:
    prefix = page_prefix(ctx, lang)
    return f"{prefix}/404.html"


def legacy_redirect_lines(ctx, lang: str) -> list[str]:
    cfg = ctx.legacy_urls if isinstance(getattr(ctx, "legacy_urls", {}), dict) else {}
    redirects = cfg.get("redirects", {}).get(lang, {}) if isinstance(cfg.get("redirects"), dict) else {}
    lines = []
    if isinstance(redirects, dict):
        for source, target in sorted(redirects.items()):
            source_path = "/" + str(source).strip("/")
            if source_path == "/":
                continue
            lines.append(f"Redirect 301 {source_path} {str(target).strip()}")
    return lines


def legacy_gone_lines(ctx) -> list[str]:
    cfg = ctx.legacy_urls if isinstance(getattr(ctx, "legacy_urls", {}), dict) else {}
    patterns = cfg.get("gone_patterns", [])
    if not isinstance(patterns, list):
        return []
    lines = []
    for pattern in patterns:
        value = str(pattern or "").strip()
        if not value:
            continue
        if value == r"^wp-login\.php$":
            lines.append("Redirect gone /wp-login.php")
        else:
            lines.append(f"RewriteRule {value} - [G,L,NC]")
    return lines


def render_htaccess(ctx, lang: str, seo_config: dict, locales) -> str:
    error_404 = htaccess_404_path(ctx, lang)
    redirects = legacy_redirect_lines(ctx, lang)
    gone = legacy_gone_lines(ctx)
    legacy_block = "\n".join(redirects + gone)
    if legacy_block:
        legacy_block = "\n# Legacy WordPress/search-index recovery.\n" + legacy_block + "\n"

    return f'''# Generated by the PCA static site builder.
# Do not edit this file directly unless you also update the generator.

Options -Indexes
DirectoryIndex index.html index.php

ErrorDocument 404 {error_404}
{legacy_block}
<IfModule mod_rewrite.c>
RewriteEngine On
RewriteCond %{{HTTPS}} !=on
RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [R=301,L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set Permissions-Policy "geolocation=(), microphone=(), camera=()"
Header always set X-Frame-Options "SAMEORIGIN"
Header always set Content-Security-Policy "default-src 'self'; img-src 'self' data: https:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline' 'unsafe-eval'; font-src 'self' data:; connect-src 'self'; frame-ancestors 'self'; base-uri 'self'; form-action 'self'"
<FilesMatch "\\.(jpg|jpeg|png|gif|css|js|woff2|woff|ttf)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
</FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml application/xml application/xhtml+xml application/rss+xml application/javascript application/json image/svg+xml
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/html "access plus 0 seconds"
ExpiresByType text/css "access plus 1 month"
ExpiresByType application/javascript "access plus 1 month"
ExpiresByType image/svg+xml "access plus 1 month"
ExpiresByType image/png "access plus 1 year"
ExpiresByType image/jpeg "access plus 1 year"
ExpiresByType image/webp "access plus 1 year"
ExpiresByType image/gif "access plus 1 year"
ExpiresByType font/woff2 "access plus 1 year"
</IfModule>

<IfModule mod_headers.c>
<FilesMatch "\\.(?:css|js|png|jpg|jpeg|gif|webp|svg|woff2)$">
Header set Cache-Control "public, max-age=31536000"
</FilesMatch>
<FilesMatch "\\.(?:html|htm|php)$">
Header set Cache-Control "no-cache, must-revalidate"
</FilesMatch>
</IfModule>

<FilesMatch "(^\\.|\\.env$|composer\\.(json|lock)$|package(-lock)?\\.json$|yarn\\.lock$|pnpm-lock\\.yaml$|.*\\.(md|py|sh|sql|bak|old|orig|log)$)">
Require all denied
</FilesMatch>
'''


def write_htaccess_files(ctx, seo_config: dict, locales, lang: str, lang_root) -> None:
    (lang_root / ".htaccess").write_text(render_htaccess(ctx, lang, seo_config, locales), encoding="utf-8")
